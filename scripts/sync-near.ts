/**
 * Refresh the NEAR deployment record and demo evidence from the sibling
 * `bound` repo (branch near-hackathon). Local only; reads no secrets: the
 * copied files hold account ids and transaction hashes. It also rewrites
 * `lib/near/evidence/index.ts`, so a redeploy or a new demo run needs only
 * this sync: no contract id or run id is written anywhere else in the app.
 *
 *   pnpm sync:near [path-to-bound-repo]   (default ../bound)
 */
import { copyFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const bound = resolve(process.argv[2] ?? "../bound");
const here = resolve("lib/near");

copyFileSync(
  join(bound, "near/deployments/testnet.json"),
  join(here, "testnet.json"),
);
const ev = join(bound, "near/evidence");
const runs = readdirSync(ev).filter((f) => /^near-demo-.*\.json$/.test(f));
for (const f of runs) copyFileSync(join(ev, f), join(here, "evidence", f));

// Every committed run in lib/near/evidence, not only the ones just copied.
const all = readdirSync(join(here, "evidence"))
  .filter((f) => /^near-demo-.*\.json$/.test(f))
  .sort();
const name = (i: number) => `run${i}`;
writeFileSync(
  join(here, "evidence", "index.ts"),
  [
    "// Generated by `pnpm sync:near`. Do not edit by hand.",
    ...all.map((f, i) => `import ${name(i)} from "./${f}";`),
    "",
    `export const EVIDENCE: readonly unknown[] = [${all.map((_, i) => name(i)).join(", ")}];`,
    "",
  ].join("\n"),
);
console.log(
  `copied testnet.json and ${runs.length} evidence file(s) from ${bound}; indexed ${all.length} run(s)`,
);
